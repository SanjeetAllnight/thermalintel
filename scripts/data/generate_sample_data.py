def validate_and_generate(output_path: Path = SAMPLE_HOTSPOTS_PATH) -> int:
    """Validate each hotspot model against the Pydantic schema and write to disk."""
    validated: List[Dict[str, Any]] = []
    for item in REALISTIC_HOTSPOTS:
        # Pydantic validation: will raise ValidationError if malformed
        hotspot = Hotspot(**item)
        validated.append(hotspot.model_dump())

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(validated, f, indent=2)

    print(f"[✓] Generated and validated {len(validated)} hotspots at: {output_path}")
    return len(validated)


